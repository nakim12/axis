#!/usr/bin/env Rscript
# Download the frozen evaluation dataset into data/eval/. Run from the repo root.
# Everything reported in docs/results.md is computed from these files, so only
# re-run this deliberately (it changes every downstream number).

suppressPackageStartupMessages({
  library(quantmod)
  library(dplyr)
})

source("R/config.R")
source("R/eval_config.R")

fetch_one <- function(ticker, from, to, attempts = 4L) {
  for (i in seq_len(attempts)) {
    x <- tryCatch(
      getSymbols(ticker, src = "yahoo", from = from, to = to,
                 auto.assign = FALSE, warnings = FALSE),
      error = function(e) e
    )
    if (!inherits(x, "error") && NROW(x) > 0) return(x)
    Sys.sleep(2 * i)
  }
  stop("Failed to download ", ticker, call. = FALSE)
}

# Yahoo treats `to` as exclusive.
from <- eval_window$start
to   <- eval_window$end + 1

tickers <- sort(unique(c(
  unlist(lapply(eval_universes, `[[`, "tickers")),
  unlist(lapply(eval_universes, function(u) names(u$benchmark$weights))),
  unname(all_stocks)
)))

prices <- bind_rows(lapply(tickers, function(tk) {
  message("Downloading ", tk)
  x <- fetch_one(tk, from, to)
  tibble(
    date     = as.Date(zoo::index(x)),
    ticker   = tk,
    close    = as.numeric(quantmod::Cl(x)),
    adjusted = as.numeric(quantmod::Ad(x))
  )
})) %>%
  filter(!is.na(adjusted), date >= eval_window$start, date <= eval_window$end) %>%
  arrange(ticker, date)

message("Downloading ", eval_riskfree_ticker)
irx <- fetch_one(eval_riskfree_ticker, from, to)
# ^IRX is the 13-week T-bill discount yield in percent, annualized.
riskfree <- tibble(
  date      = as.Date(zoo::index(irx)),
  irx_pct   = as.numeric(quantmod::Cl(irx))
) %>%
  filter(!is.na(irx_pct), date >= eval_window$start, date <= eval_window$end) %>%
  arrange(date)

dir.create(eval_data_dir, recursive = TRUE, showWarnings = FALSE)
prices_path   <- file.path(eval_data_dir, "prices.rds")
riskfree_path <- file.path(eval_data_dir, "riskfree.rds")
saveRDS(prices,   prices_path,   compress = "xz")
saveRDS(riskfree, riskfree_path, compress = "xz")

coverage <- prices %>%
  group_by(ticker) %>%
  summarise(first = min(date), last = max(date), rows = n(), .groups = "drop")

md5 <- tools::md5sum(c(prices_path, riskfree_path))

manifest <- c(
  "# Evaluation data snapshot",
  "",
  "Generated by `scripts/build_eval_data.R`. Do not edit by hand.",
  "",
  paste0("- Downloaded: ", format(Sys.time(), "%Y-%m-%d %H:%M %Z")),
  paste0("- Source: Yahoo Finance via quantmod ", as.character(packageVersion("quantmod"))),
  paste0("- Window: ", eval_window$start, " to ", eval_window$end),
  paste0("- Risk-free: ", eval_riskfree_ticker, " (", nrow(riskfree), " rows, ",
         min(riskfree$date), " to ", max(riskfree$date), ")"),
  "",
  "## Checksums (MD5)",
  "",
  paste0("- `", basename(names(md5)), "`: ", unname(md5)),
  "",
  "## Tickers",
  "",
  "| Ticker | First | Last | Rows |",
  "|---|---|---|---|",
  sprintf("| %s | %s | %s | %d |", coverage$ticker, coverage$first, coverage$last, coverage$rows)
)
writeLines(manifest, file.path(eval_data_dir, "MANIFEST.md"))

message("Wrote ", nrow(prices), " price rows for ", length(tickers), " tickers.")
